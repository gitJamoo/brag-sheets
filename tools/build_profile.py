#!/usr/bin/env python3
"""Builds profile.json, the one-request summary of every sheet for AI agents.

Run from the repo root after editing any sheet:  python3 tools/build_profile.py
Every value is copied from a sheet (front matter, hero image, resume-ready
bullets, Short line); nothing here is written by hand except `highlights`.
"""
import json, re
from pathlib import Path

REPO = "https://github.com/gitJamoo/brag-sheets"
BLOB = REPO + "/blob/main/"
ROOT = Path(__file__).resolve().parent.parent

# The strongest claims, each pointing at the sheet that backs it.
HIGHLIGHTS = [
    ("Shipped 2 production AI agents at Magical that run daily on every customer automation: one reviews every workflow change and proposes patches; one fixes live failures autonomously, raising real-world accuracy to 95%.", "experience/magical/brag.md"),
    ("Proposed and led a switch to cheaper, better agent models at Magical with no regressions, saving an estimated $450K a year, enabled by an evals and benchmarking engine he rebuilt from scratch.", "experience/magical/brag.md"),
    ("As an AI Consultant, built a production AI quoting agent (Claude via OpenRouter, N8N, SQL Server) that saved each trader ~10 hours a month and moved $150K+ in revenue.", "experience/independent-ai-consulting/brag.md"),
    ("At The Estée Lauder Companies, worked on a recommendation chatbot projected at $1.5M in revenue across 12,000 live SKUs and 30+ brand databases.", "experience/estee-lauder/brag.md"),
    ("Solo-built and launched EcoDues, a live open-source SaaS, in about 10 days.", "project/ecodues/brag.md"),
    ("Co-founded Envolvly, which won Oregon State's school-wide startup pitch competition.", "project/envolvly/brag.md"),
    ("B.S. Computer Science, Oregon State University (Cum Laude, 2026), while competing as an NCAA Division I athlete 20+ hours a week.", "education/oregon-state/brag.md"),
]


def front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            if v.strip():
                out[k.strip()] = v.strip()
    return out


def section(text, name):
    m = re.search(r"^## [^\n]*" + name + r"[^\n]*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    return m.group(1) if m else ""


def clean(s):
    return re.sub(r"\*\*|`", "", s).strip()


def sheet(path):
    text = path.read_text()
    rel = path.relative_to(ROOT).as_posix()
    fm = front_matter(text)
    hero = re.search(r"<!-- hero -->\n!\[([^\]]*)\]\((\S+)\)", text)
    bullets_md = section(text, "Resume-ready")
    bullets = [clean(b) for b in re.findall(r"^- (.+)$", bullets_md, re.M)]
    short = re.search(r"^\*\*Short:\*\*\s*(.+)$", text, re.M)
    images = sorted(set(re.findall(r"!\[[^\]]*\]\((https://raw\.githubusercontent\.com/\S+?\.(?:png|jpe?g|webp|gif))\)", text)))
    entry = {
        "type": fm.get("type"),
        "title": clean(fm.get("title", "")),
        "org": fm.get("org"),
        "role": fm.get("role"),
        "location": fm.get("location"),
        "dates": fm.get("dates"),
        "live": fm.get("live"),
        "repo": fm.get("repo") or fm.get("repos"),
        "summary": clean(short.group(1)) if short else None,
        "hero_image": {"url": hero.group(2), "caption": hero.group(1)} if hero else None,
        "resume_bullets": bullets,
        "images": images,
        "sheet": BLOB + rel,
    }
    return {k: v for k, v in entry.items() if v not in (None, "", [])}


def main():
    sheets = sorted(ROOT.glob("*/**/brag.md"))
    by = {"profile": [], "experience": [], "education": [], "project": []}
    for p in sheets:
        e = sheet(p)
        by.setdefault(e.get("type", "project"), []).append(e)
    # newest work first
    for k in ("experience", "project"):
        by[k].sort(key=lambda e: e.get("dates", ""), reverse=True)
    profile = by["profile"][0] if by["profile"] else {}
    data = {
        "$comment": "Generated by tools/build_profile.py from the sheets in this repo. The sheets are the source of truth; cite them.",
        "name": "James M. Smith",
        "headline": "AI/Product Engineer at Magical, San Francisco",
        "location": "San Francisco, CA",
        "email": "real.jamesmsmith@gmail.com",
        "links": {
            "portfolio": "https://j-m-s.dev",
            "resume": "https://j-m-s.dev/resume/print",
            "linkedin": "https://www.linkedin.com/in/james-m-smith1",
            "github": "https://github.com/gitJamoo",
            "brag_sheets": REPO,
        },
        "photo": profile.get("hero_image"),
        "highlights": [{"claim": c, "source": BLOB + s} for c, s in HIGHLIGHTS],
        "experience": by["experience"],
        "education": by["education"],
        "projects": by["project"],
    }
    (ROOT / "profile.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(f"profile.json: {len(by['experience'])} roles, {len(by['education'])} education, {len(by['project'])} projects")


if __name__ == "__main__":
    main()
